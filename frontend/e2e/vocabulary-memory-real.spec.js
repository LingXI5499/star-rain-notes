function tone() {
  const samples=4000, bytes=Buffer.alloc(44+samples*2)
  bytes.write('RIFF',0);bytes.writeUInt32LE(bytes.length-8,4);bytes.write('WAVEfmt ',8);bytes.writeUInt32LE(16,16)
  bytes.writeUInt16LE(1,20);bytes.writeUInt16LE(1,22);bytes.writeUInt32LE(8000,24);bytes.writeUInt32LE(16000,28);bytes.writeUInt16LE(2,32);bytes.writeUInt16LE(16,34);bytes.write('data',36);bytes.writeUInt32LE(samples*2,40)
  for(let index=0;index<samples;index++)bytes.writeInt16LE(Math.round(Math.sin(index*2*Math.PI*440/8000)*1000),44+index*2)
  return bytes
}
