import { test, expect } from './fixtures'

test('outline stays beside document and supports resizing, hiding and persisted canvas width', async ({ page, fixture }) => {
  fixture.article.bodyMarkdown = Array.from({ length: 60 }, (_, i) => `## 章节 ${i}\n\n正文内容 ${i}\n`).join('\n')
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('/blog/editor/1')
  const editor = page.locator('.markdown-editor')
  const outline = editor.getByRole('complementary', { name: '文档大纲' })
  const input = editor.locator('.vditor-ir [contenteditable=true]')
  await expect(input).toBeVisible({ timeout: 20000 })
  await input.evaluate(el => { el.dataset.layoutIdentity = 'original' })
  const bounds = async () => ({ outline: await outline.boundingBox(), host: await editor.locator('.markdown-editor__host').boundingBox(), shell: await editor.boundingBox() })
  let b = await bounds()
  expect(b.outline.x).toBeGreaterThanOrEqual(b.shell.x)
  expect(Math.abs(b.outline.y - b.host.y)).toBeLessThan(1)
  expect(Math.abs(b.outline.height - b.host.height)).toBeLessThan(1)
  expect(b.outline.x + b.outline.width).toBeLessThan(b.host.x)
  await page.screenshot({ path: '../.local/editor-outline-layout-normal.png' })
  const initialWidth = b.outline.width
  const divider = editor.getByRole('separator', { name: '调整大纲宽度' })
  const d = await divider.boundingBox()
  await page.mouse.move(d.x + d.width / 2, d.y + 40)
  await page.mouse.down()
  await page.mouse.move(d.x + 84, d.y + 40, { steps: 8 })
  await page.mouse.up()
  b = await bounds()
  expect(b.outline.width).toBeGreaterThan(initialWidth + 60)
  await divider.focus()
  await page.keyboard.press('Home')
  await expect(divider).toHaveAttribute('aria-valuenow', '160')
  await page.keyboard.press('ArrowRight')
  await expect(divider).toHaveAttribute('aria-valuenow', '176')
  await editor.getByRole('button', { name: '隐藏大纲' }).first().click()
  await expect(outline).toHaveCount(0)
  await editor.getByRole('button', { name: '显示大纲' }).click()
  await expect(divider).toHaveAttribute('aria-valuenow', '176')
  await expect(input).toHaveAttribute('data-layout-identity', 'original')
  await expect(editor.locator('.editor-outline')).toContainText('章节 59')
  await editor.getByRole('slider', { name: '正文画幅宽度' }).fill('480')
  await expect(editor.locator('output')).toHaveText('480px')
  const narrowPadding = await editor.locator('.vditor-ir').evaluate(el => parseFloat(getComputedStyle(el).paddingLeft))
  await editor.getByRole('slider', { name: '正文画幅宽度' }).fill('800')
  const widePadding = await editor.locator('.vditor-ir').evaluate(el => parseFloat(getComputedStyle(el).paddingLeft))
  expect(narrowPadding).toBeGreaterThan(widePadding)
  await editor.getByRole('slider', { name: '正文画幅宽度' }).fill('480')
  await editor.getByRole('button', { name: '全屏', exact: true }).click()
  b = await bounds()
  expect(Math.abs(b.outline.height - b.host.height)).toBeLessThan(1)
  await page.screenshot({ path: '../.local/editor-outline-layout-desktop.png' })
  await page.keyboard.press('Escape')
  await page.reload()
  await expect(input).toBeVisible({ timeout: 20000 })
  await expect(divider).toHaveAttribute('aria-valuenow', '176')
  await expect(editor.locator('output')).toHaveText('480px')
  await editor.getByRole('button', { name: '铺满', exact: true }).click()
  await expect(editor.locator('output')).toHaveText('铺满')
  await page.setViewportSize({ width: 390, height: 700 })
  await editor.getByRole('button', { name: '全屏', exact: true }).click()
  await expect(divider).toBeHidden()
  b = await bounds()
  expect(b.outline.width).toBeLessThanOrEqual(390)
  expect(b.outline.y + b.outline.height).toBeLessThanOrEqual(b.host.y)
  expect(b.host.height).toBeGreaterThan(200)
  await page.screenshot({ path: '../.local/editor-outline-layout-mobile.png' })
  await editor.getByRole('button', { name: '隐藏大纲' }).first().click()
  await expect(input).toBeVisible()
})
