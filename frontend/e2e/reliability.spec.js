test('fast SPA article switch cannot be overwritten by the delayed previous route', async ({ page, fixture }) => {
  let finish; fixture.blogDelays.a = new Promise(resolve => { finish = resolve })
  await page.goto('/blog')
  await page.locator('a[href="/blog/posts/a"]').first().click()
  await expect(page).toHaveURL(/\/blog\/posts\/a$/)
  await page.goBack()
  await expect(page).toHaveURL(/\/blog$/)
  await page.locator('a[href="/blog/posts/b"]').first().click()
  await expect(page.getByRole('heading', { name: 'Article B', exact: true })).toBeVisible()
  finish(); await page.waitForTimeout(150)
  await expect(page.getByRole('heading', { name: 'Article B', exact: true })).toBeVisible()
  await expect(page.locator('main')).toHaveCount(1)
})
test('portfolio filters retain the current scroll position and URL state', async ({ page }) => {
  await page.goto('/portfolio')
  await expect(page.locator('.works-featured .works-card')).toHaveCount(3)
  const filter = page.getByRole('button', { name: '工具', exact: true })
  await filter.scrollIntoViewIfNeeded()
  await filter.evaluate(element => window.scrollTo({ top: element.getBoundingClientRect().top + scrollY - 160, behavior: 'instant' }))
  const before = await page.evaluate(() => scrollY)
  // Use the actual visible click point: locator.click's pre-action scroll is not the filter behavior.
  const point = await filter.boundingBox()
  await page.mouse.click(point.x + point.width / 2, point.y + point.height / 2)
  await expect(page).toHaveURL(/categoryId=1/)
  await expect.poll(() => page.evaluate(value => Math.abs(scrollY - value), before)).toBeLessThan(10)
  const beforeReload = await page.evaluate(() => scrollY)
  await page.reload(); await expect(page.getByRole('button', { name: '工具', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect.poll(() => page.evaluate(value => Math.abs(scrollY - value), beforeReload)).toBeLessThan(10)
})
